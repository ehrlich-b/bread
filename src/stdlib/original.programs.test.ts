// Read source-derived logical root pins without depending on incidental lane IDs.
type PinMap = {
  element: number;
  source_pin: string;
  source_bit: number;
  bread_net: string;
};
const rootPins = new Map((manual.metadata!.pin_map as PinMap[]).filter((pin) => pin.bread_net)
  .map((pin) => [`${pin.element}.${pin.source_pin}.${pin.source_bit}`, pin.bread_net]));
function rootNet(element: number, pin: string, bit = 0): string {
  const net = rootPins.get(`${element}.${pin}.${bit}`);
  if (!net)
    throw new Error(`Missing root source pin ${element}.${pin}[${bit}]`);
  return net;
}
function rootWord(s: Simulator, element: number, pin: string, width: number): number | string {
  let value = 0;
  for (let bit = 0; bit < width; bit++) {
    const n = s.readNet(rootNet(element, pin, bit));
    if (n !== 0 && n !== 1) return String(n);
    value += n * 2 ** bit;
  }
  return value;
}
function rootReg(s: Simulator, element: number): number | string {
  let value = 0;
  for (let bit = 0; bit < 8; bit++) {
    const n = s.readNet(rootNet(element, `Q${bit}`));
    if (n !== 0 && n !== 1) return String(n);
    value += n * 2 ** bit;
  }
  return value;
}
function snapshot(s: Simulator) {
  return {
    PC: rootWord(s, 20, 'out', 8), A: rootReg(s, 0), B: rootReg(s, 1),
    IR: rootReg(s, 7), MAR: rootReg(s, 29), OUT: rootReg(s, 34),
    SP: rootWord(s, 117, 'Q', 8), Rdy: s.readNet(rootNet(83, 'ovf')),
    boot: rootWord(s, 83, 'out', 5), Hlt: s.readNet(rootNet(68, 'Hlt')),
    RstDone: s.readNet(rootNet(68, 'RstDone')), cpuClock: s.readNet(rootNet(20, 'C')),
  };
}
function runtimePin(s: Simulator, id: string, pin: string): NetState {
  const component = s.graph.components[s.graph.componentById.get(id)!];
  if (!component)
    throw new Error('Missing runtime component ' + id);
  const index = component.pins.findIndex(p => p.name === pin);
  if (index < 0)
    throw new Error(`Missing runtime pin ${id}.${pin}`);
  return s.graph.nets[component.pinNetIdx[index]!]!.value;
}
function runtimeWord(s: Simulator, id: string, label: string, width: number): number | string {
  let value = 0;
  for (let i = 0; i < width; i++) {
    const n = runtimePin(s, id, label + i);
    if (n !== 0 && n !== 1)
      return String(n);
    value += n * 2 ** i;
  }
  return value;
}
function mpc(s: Simulator): number | string {
  let value = 0;
  for (let i = 0; i < 3; i++) {
    const n = runtimePin(s, 'v68__v20__counter', `Q${i}`);
    if (n !== 0 && n !== 1)
      return String(n);
    value += n * 2 ** i;
  }
  return value;
}
function memory(s: Simulator): Array<number | string> {
  const regs = [0, 5, 6, 7, 8, 9, 10, 11], words: Array<number | string> = [];
  for (let bank = 0; bank < 4; bank++)
    for (const reg of regs) {
      let value = 0, unknown: string | undefined;
      for (let bit = 0; bit < 8; bit++) {
        const n = runtimePin(s, `v31__v${bank}__v${reg}__bit${bit}`, 'Q');
        if (n !== 0 && n !== 1)
          unknown = String(n);
        else
          value += n * 2 ** bit;
      }
      words.push(unknown ?? value);
    }
  return words;
}
function architecture(s: Simulator) {
  const basic = snapshot(s), flag = rootReg(s, 94);
  return {
    ...basic, MPC: mpc(s), ram: memory(s),
    flags: typeof flag === 'number' ? { eq: Boolean(flag & 4), greater: Boolean(flag & 2), zero: Boolean(flag & 1) } : flag,
  };
}
function stable(s: Simulator) {
  const state = snapshot(s);
  const unknown = Object.entries(state).filter(([, value]) => value === 'X' || value === 'Z');
  const bus = Array.from({ length: 8 }, (_, bit) => s.readNet(rootNet(20, 'in', bit)));
  const contention = s.graph.nets.filter(n => n.value === 'X' && n.drivers.some(d => s.graph.components[d.comp]!.outputBuf[d.outIdx] === 0) && n.drivers.some(d => s.graph.components[d.comp]!.outputBuf[d.outIdx] === 1)).map(n => n.id);
  return { architectural_unknowns: unknown, bus, stable_contention: contention };
}
type ExpectedProgram = ReferenceRun;
function runProgram(program: ExpectedProgram, resetBeforeBoot = false) {
  const fixture = structuredClone(manual);
  const rom = fixture.components.find(c => c.id === 'v82')!;
  rom.params!.contents = 'v2.0 raw\n' + program.program_bytes.map(v => v.toString(16)).join('\n');
  const s = new Simulator(loadCircuit(fixture));
  s.settle();
  const initial = { ...architecture(s), stable: stable(s) };
  if (resetBeforeBoot) {
    s.setComponentInput('v116', 'Y', 1);
    s.settle();
    s.setComponentInput('v116', 'Y', 0);
    s.settle();
  }
  const phases: Array<Record<string, unknown>> = [], boundaries: Array<Record<string, unknown>> = [], outputs: number[] = [];
  let halted = false;
  let bootPulses = 0;
  let cpuPulses = 0;
  for (let cycle = 0; cycle < 3000; cycle++) {
    if (s.readNet(rootNet(83, 'ovf')) === 0) {
      s.setComponentInput('v84', 'Y', 1);
      s.settle();
      bootPulses++;
      s.setComponentInput('v84', 'Y', 0);
      s.settle();
      phases.push({ cycle, phase: 'boot', ...architecture(s), stable: stable(s) });
      continue;
    }
    const controls = runtimeWord(s, 'v68__v0', 'D', 29);
    const ldOut = s.readNet(rootNet(68, 'LdOut'));
    const previousClock = s.readNet(rootNet(20, 'C'));
    s.setComponentInput('v2', 'Y', 1);
    s.settle();
    cpuPulses++;
    const after = architecture(s);
    const status = stable(s);
    phases.push({ cycle, phase: 'primary-high', control_word: controls, ...after, stable: status });
    assert.equal(status.architectural_unknowns.length, 0);
    assert.equal(status.stable_contention.length, 0);
    if (previousClock === 0 && after.cpuClock === 1 && ldOut === 1) {
      assert.equal(typeof after.OUT, 'number');
      outputs.push(after.OUT as number);
    }
    if (typeof controls === 'number' && (controls & (2 ** 20)) !== 0 && after.cpuClock === 1)
      boundaries.push({ cycle, ...after });
    s.setComponentInput('v2', 'Y', 0);
    s.settle();
    const low = architecture(s), lowStatus = stable(s);
    phases.push({ cycle, phase: 'primary-low', ...low, stable: lowStatus });
    assert.equal(lowStatus.architectural_unknowns.length, 0);
    assert.equal(lowStatus.stable_contention.length, 0);
    if (low.Hlt === 1) {
      boundaries.push({ cycle, ...low });
      halted = true;
      break;
    }
  }
  assert(halted, `CPU did not halt in bounded test: ${JSON.stringify(architecture(s))}`);
  quiet(s);
  return { s, initial, final: architecture(s), phases, boundaries, outputs, bootPulses, cpuPulses };
}
function compareProgram(run: ReturnType<typeof runProgram>, oracle: ReferenceRun, name: string): void {
  assert.deepEqual(run.outputs, oracle.output_history);
  assert.equal(run.boundaries.length, oracle.instructions.length);
  const fields = [['PC', 'pc'], ['A', 'a'], ['B', 'b'], ['OUT', 'out'], ['SP', 'sp']] as const;
  for (let i = 0; i < run.boundaries.length; i++) {
    const observed = run.boundaries[i]!, expected = oracle.instructions[i]!.after;
    for (const [actual, key] of fields)
      assert.equal(observed[actual], expected[key], `${name}: instruction ${i} ${actual}`);
    assert.deepEqual(observed.flags, expected.flags, `${name}: instruction ${i} flags`);
    assert.deepEqual(observed.ram, expected.ram, `${name}: instruction ${i} RAM`);
    assert.equal(observed.Hlt, Number(expected.halted), `${name}: instruction ${i} halt`);
  }
  // The raw oscillators may keep toggling after HLT; storage must stay fixed.
  const before = architecture(run.s);
  for (let pulse = 0; pulse < 20; pulse++) {
    run.s.setComponentInput('v2', 'Y', 1);
    run.s.settle();
    run.s.setComponentInput('v2', 'Y', 0);
    run.s.settle();
  }
  assert.deepEqual(architecture(run.s), before);
}
