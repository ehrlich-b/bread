test('HALT/reset from original CALLRET, flags retained and program reruns', () => {
  const oracle = programs['callret']!;
  const run = runProgram(oracle);
  const s = run.s;
  const halted = architecture(s);
  assert.equal(halted.cpuClock, 0);
  s.setComponentInput('v116', 'Y', 1);
  s.settle();
  s.setComponentInput('v116', 'Y', 0);
  s.settle();
  const phases: Array<Record<string, unknown>> = [];
  const outputs: number[] = [];
  let restarted = false;
  for (let cycle = 0; cycle < 3000; cycle++) {
    if (s.readNet(rootNet(83, 'ovf')) === 0) {
      restarted = true;
      s.setComponentInput('v84', 'Y', 1);
      s.settle();
      s.setComponentInput('v84', 'Y', 0);
      s.settle();
      phases.push({ cycle, phase: 'boot', ...architecture(s), stable: stable(s) });
      continue;
    }
    const ldOut = s.readNet(rootNet(68, 'LdOut')), oldClock = s.readNet(rootNet(20, 'C'));
    s.setComponentInput('v2', 'Y', 1);
    s.settle();
    const high = architecture(s);
    phases.push({ cycle, phase: 'primary-high', ...high, stable: stable(s) });
    if (ldOut === 1 && oldClock === 0 && high.cpuClock === 1)
      outputs.push(high.OUT as number);
    s.setComponentInput('v2', 'Y', 0);
    s.settle();
    phases.push({ cycle, phase: 'primary-low', ...architecture(s), stable: stable(s) });
    if (restarted && s.readNet(rootNet(68, 'Hlt')) === 1)
      break;
  }
  const final = architecture(s);
  assert(restarted);
  assert.equal(final.Hlt, 1);
  assert.equal(final.A, 10);
  assert.equal(final.PC, 16);
  assert.deepEqual(outputs, [0, ...oracle.output_history]);
  quiet(s);
  for (const phase of phases) {
    const status = phase.stable as ReturnType<typeof stable>;
    assert.equal(status.architectural_unknowns.length, 0);
    assert.equal(status.stable_contention.length, 0);
  }
  const afterClear = phases.find(p => p.A === 0 && p.OUT === 0 && p.boot === 0);
  assert(afterClear);
  assert.deepEqual(afterClear.flags, halted.flags);
  assert.equal((afterClear.ram as number[])[31], halted.ram[31], 'warm loader retains stack byte 31');
});
