function wrap(name: string): Simulator {
  const d = byName.get(name)!;
  if (!d)
    throw new Error('Unknown definition ' + name);
  const closure = new Map<string, CircuitJSON>();
  function add(n: string): void {
    if (closure.has(n)) return;
    const def = byName.get(n);
    if (!def) return;
    closure.set(n, def);
    for (const c of def.components) add(c.type);
  }
  add(name);
  const obj: CircuitJSON = { version: 1, kind: 'circuit', name: 'Generated test harness for ' + name, components: [{ id: 'U', type: name }], nets: d.ports!.map(p => ({ id: p.name, endpoints: [`U.${p.name}`] })), definitions: [...closure.values()] };
  const sim = new Simulator(loadCircuit(obj));
  for (const p of d.ports!)
    if (p.dir === 'in')
      sim.setInput(p.name, 0);
  sim.settle();
  return sim;
}
function set(sim: Simulator, pin: string, value: NetState) { sim.setInput(pin, value); }
function word(sim: Simulator, label: string, width: number, value: number): void {
  for (let i = 0; i < width; i++) {
    set(sim, width === 1 ? label : `${label}_${i}`, ((value >>> i) & 1) as NetState);
  }
}
function read(sim: Simulator, label: string, width: number): number | string {
  let value = 0;
  for (let i = 0; i < width; i++) {
    const n = sim.readNet(width === 1 ? label : `${label}_${i}`);
    if (n !== 0 && n !== 1)
      return String(n);
    value += n * 2 ** i;
  }
  return value;
}
function edge(sim: Simulator, clk: string = 'C'): void {
  set(sim, clk, 0); sim.settle();
  set(sim, clk, 1); sim.settle();
}
