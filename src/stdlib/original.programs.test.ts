    const boundaries: Array<ReturnType<typeof architecture>> = [];
    let ticks = 0;
    for (; ticks < 50000; ticks++) {
      const oldClock = sim.readNet(rootNet(20, 'C'));
      const controls = runtimeWord(sim, 'v68__v0', 'D', 29);
      const loadOutput = sim.readNet(rootNet(68, 'LdOut'));
      sim.tick();
      const clock = sim.readNet(rootNet(20, 'C'));
      if (oldClock === 0 && clock === 1) {
        const after = architecture(sim);
        if (loadOutput === 1)
          outputs.push(after.OUT);
        if (typeof controls === 'number' && (controls & 2 ** 20) !== 0)
          boundaries.push(after);
      }
      if (sim.readNet(rootNet(68, 'Hlt')) === 1) {
        boundaries.push(architecture(sim));
        break;
      }
    }
    assert.equal(sim.readNet(rootNet(68, 'Hlt')), 1);
    assert.deepEqual(outputs, oracle.output_history);
    assert.equal(boundaries.length, oracle.instructions.length);
    for (let index = 0; index < boundaries.length; index++) {
      const actual = boundaries[index]!, expected = oracle.instructions[index]!.after;
      for (const [field, key] of [['PC', 'pc'], ['A', 'a'], ['B', 'b'], ['OUT', 'out'], ['SP', 'sp']] as const)
        assert.equal(actual[field], expected[key]);
      assert.deepEqual(actual.flags, expected.flags);
      assert.deepEqual(actual.ram, expected.ram);
      assert.equal(actual.Hlt, expected.halted ? 1 : 0);
    }
    quiet(sim);
    const halted = architecture(sim);
    for (let tick = 0; tick < 50; tick++)
      sim.tick();
    assert.deepEqual(architecture(sim), halted);
